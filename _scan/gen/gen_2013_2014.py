import json, io, os, re

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))


def clean(s):
    """前端不渲染 markdown，把 **x** 统一改为中文引号「x」"""
    if not isinstance(s, str):
        return s
    return re.sub(r"\*\*(.+?)\*\*", r"「\1」", s)


def dump(year, doc):
    doc["year"] = year
    for q in doc["questions"]:
        q.setdefault("options", [])
        q.setdefault("images", [])
        q.setdefault("answer_images", [])
        q.setdefault("tags", [])
        for f in ("stem", "answer", "explanation"):
            q[f] = clean(q.get(f))
        for o in q["options"]:
            o["text"] = clean(o["text"])
    p = os.path.join(ROOT, "data", "source", "%d.json" % year)
    with io.open(p, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(p, len(doc["questions"]), "题")


def opt(*pairs):
    return [{"key": k, "text": t} for k, t in pairs]


def Q(**kw):
    return kw


