def _score(text, kws):
    total = hits = 0
    first = 10 ** 6
    for kw in kws:
        n = text.count(kw)
        if n:
            total += len(kw) * min(n, 2)
            hits += 1
            first = min(first, text.find(kw))
    return total, hits, first


def classify(text, fallback_chapter, kp_chapter):
    """两级判定：先按章节关键词定章，再在章内按知识点关键词定知识点。

    返回 (knowledge_points, chapter, score, special_tag)
    """
    for kws, ch, kp, tag in SPECIAL_RULES:
        if any(k in text for k in kws):
            return [kp], ch, 99, tag

    ch_scores = [(sc[0], sc[1], -sc[2], ch) for ch, kws in CHAPTER_KW.items()
                 for sc in [_score(text, kws)] if sc[0]]
    if ch_scores:
        ch_scores.sort(reverse=True)
        chapter = ch_scores[0][3]
    else:
        chapter = fallback_chapter or ""

    if not chapter:
        return [], "", 0, ""

    kp_scores = [(sc[0], sc[1], -sc[2], kp) for kp, kws in KP_RULES.items()
                 if kp_chapter.get(kp) == chapter
                 for sc in [_score(text, kws)] if sc[0]]
    if not kp_scores:
        return [], chapter, 0, ""
    kp_scores.sort(reverse=True)
    top = kp_scores[0][0]
    kps = [row[3] for row in kp_scores if row[0] >= top * 0.55][:2]
    return kps, chapter, top, ""


def build_refs(matches):
    refs, seen = [], set()
    for q, r in matches:
        for y in q["source_years"]:
            num = (q.get("original_numbers") or {}).get(str(y), "")
            key = (y, num, q["id"])
            if key in seen:
                continue
            seen.add(key)
            refs.append({"year": y, "number": num, "question_id": q["id"]})
    refs.sort(key=lambda x: (x["year"], x["number"]))
    return refs


def find_real_matches(stem_n, real_index, threshold=0.86, ratio_guard=0.55):
    """在真题里找同题（可能多年合并），返回 [(真题, 相似度)]。"""
    out = []
    for n, q in real_index:
        if not n:
            continue
        if min(len(n), len(stem_n)) / max(len(n), len(stem_n)) < ratio_guard:
            continue
        r = sim(stem_n, n)
        if r >= threshold:
            out.append((q, r))
    if not out:
        return []
    out.sort(key=lambda t: -t[1])
    # 只保留与最高分接近的（同题的不同年份写法）
    top = out[0][1]
    return [(q, r) for q, r in out if r >= max(threshold, top - 0.06)]


