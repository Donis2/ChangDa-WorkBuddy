# ---------- 2015-计算-03 轴承（反装） ----------
q = qs['2015-计算-03']
q['answer'] = (
    "① 内部（派生）轴向力：\n"
    "$$F_{S1}=0.7F_{R1}=0.7\\times2500=1750\\ \\text{N},\\qquad F_{S2}=0.7F_{R2}=0.7\\times5000=3500\\ \\text{N}$$\n"
    "方向：反装（背靠背）时两轴承的内部轴向力**相背**（各自指向轴承外侧）——$F_{S1}$ 向左、$F_{S2}$ 向右。\n"
    "② 判压紧端：$F_A$ 指向左（轴承 1 一侧），与 $F_{S1}$ 同向。\n"
    "$$F_{S1}+F_A=1750+1000=2750\\ \\text{N}<F_{S2}=3500\\ \\text{N}$$\n"
    "说明「向左的推力」不足以顶开轴承 2 的派生力，轴被 $F_{S2}$ 推向左端，故「轴承 1 被压紧、轴承 2 被放松」。\n"
    "③ 轴向载荷（压紧端取另一端的派生力加外载荷，放松端取自身派生力）：\n"
    "$$F_{a2}=F_{S2}=3500\\ \\text{N},\\qquad F_{a1}=F_{a2}-F_A=3500-1000=2500\\ \\text{N}$$\n"
    "校验：① $F_{a1}-F_{S1}=2500-1750=750\\ \\text{N}>0$，轴承 1 确实被压紧；② $F_{a2}-F_{a1}=1000\\ \\text{N}=F_A$，轴向力平衡。"
)
q['explanation'] = (
    "考点：成对圆锥滚子轴承（反装）的轴向载荷计算。判据：① 先算派生力 $F_S=0.7F_R$ 并定出方向（反装相背、正装相向）；"
    "② 比较「$F_{S1}+F_A$」与「$F_{S2}$」，小的一侧被压紧；③ 压紧端 $F_a$ = 放松端 $F_S$ ± $F_A$，"
    "放松端 $F_a=F_S$；④ 必须用两条校核：$F_a\\ge F_S$（否则该端根本不会被压紧）和 $\\sum F_a=F_A$。"
    "原手写答案给 3500/2500，与上述校核一致（即 $F_{a1}=2500$、$F_{a2}=3500$）；"
    "原库曾改成 1750/2750，但那组数值连 $F_{a2}=2750<F_{S2}=3500$ 都不满足——轴承 2 实际承受的轴向载荷不可能小于它自己的派生力，"
    "故已改回 2500/3500。"
)

