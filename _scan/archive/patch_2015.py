# ---------- 2015-分析-01 四杆机构设计 ----------
q = qs['2015-分析-01']
q['answer'] = (
    "先判断是否满足格拉肖夫条件：最短杆 $L_{BC}=150$，最长杆 $L_{AD}=400$，\n"
    "$$150+400=550<350+320=670$$\n"
    "满足「最短杆 + 最长杆 ≤ 其余两杆之和」，故该组杆件取何种基本型式只取决于「选哪一根杆作机架」。\n\n"
    "（1）曲柄摇杆机构：以「最短杆的相邻杆」为机架。\n"
    "取 $AB$（350）为机架，则两连架杆为 $BC$（150）与 $AD$（400）、连杆为 $CD$（320）。"
    "最短杆 $BC$ 作连架杆，能整周回转，即为「曲柄」；另一连架杆 $AD$（最长杆）只能摆动，为「摇杆」；"
    "$CD$ 为连杆。机构运动简图：机架 $AB$，曲柄 $BC$，连杆 $CD$，摇杆 $AD$。\n"
    "（也可取 $CD$（320）为机架，此时最短杆 $BC$ 同样是连架杆、为曲柄，另一连架杆 $AB$ 为摇杆、$AD$ 为连杆。）\n\n"
    "（2）双摇杆机构：以「最短杆的对边」为机架。\n"
    "最短杆 $BC$ 的对边是 $AD$。取 $AD$（400）为机架，则两连架杆为 $AB$（350）与 $CD$（320）、连杆为 $BC$（150）。"
    "最短杆 $BC$ 变成连杆，两个连架杆都只能摆动、不能整周回转，故为双摇杆机构。\n"
    "（另一个办法：不满足格拉肖夫条件时无论取哪根杆为机架都是双摇杆，但本题满足条件，必须取最短杆的对边为机架。）"
)
q['explanation'] = (
    "考点：格拉肖夫条件与机架选择。**机架选谁决定机构型式**：最短杆为连架杆 → 曲柄摇杆；最短杆为机架 → 双曲柄；"
    "最短杆为连杆（即取最短杆的对边为机架）→ 双摇杆。本题的易错点是（1）中把摇杆与连杆写反——"
    "以 $AB$ 为机架时，连架杆是 $BC$ 与 $AD$，所以摇杆是最长杆 $AD$（400）、连杆才是 $CD$（320）。"
    "（原库此处标反，已更正。）"
)

# ---------- 2015-分析-02 自由度 ----------
q = qs['2015-分析-02']
q['answer'] = (
    "识别特殊结构：\n"
    "- 「复合铰链」：$D$ 处（杆 $GD$、杆 $DE$、杆 $DC$ 三构件汇交，按 2 个转动副计）；\n"
    "- 「局部自由度」：滚子 $A$（自转不影响输出运动，计算时与摆杆 $CA$ 视为一体）；\n"
    "- 「虚约束」：顶部水平杆的两端 $H$、$K$ 都与机架组成移动副、两条导路重合，属重复约束，计算时只计 1 个移动副"
    "（$G$ 是水平杆上的铰点，不是机架点）。\n\n"
    "去除虚约束后：$n=7$（水平杆、杆 $GD$、杆 $DE$、杆 $FE$、杆 $DC$、杆 $CA$、凸轮），"
    "$P_L=9$（$H$ 处移动副 1 + $G$ 处铰 1 + $D$ 处 2 + $E$ 处 1 + $F$ 处 1 + $C$ 处 1 + $A$ 处 1 + 凸轮中心 1），"
    "$P_H=1$（滚子 $A$ 与凸轮）：\n"
    "$$F=3n-2P_L-P_H=3\\times7-2\\times9-1=2$$\n"
    "原动件数 $W=1<F=2$，故机构「没有确定的运动」（运动不确定）。"
)
q['explanation'] = (
    "考点：复合铰链、局部自由度、虚约束的识别与自由度计算。本题的虚约束是「同一构件（顶部水平杆）与机架组成两个"
    "导路重合的移动副」，位置在 $H$、$K$ 两端；$G$ 只是水平杆上的一个铰点，把虚约束记到 $G$ 上是错的。"
    "算得 $F=2$ 而原动件只有 1 个，运动才不确定——这正是本题的落脚点。"
    "（原库把虚约束位置误记为「$G$、$H$ 之一」，已更正。）"
)

# ---------- 2015-计算-02 锥齿轮-斜齿轮 ----------
