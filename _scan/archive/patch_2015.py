    "按图示 $n_1$ 方向判定，斜齿轮 3 取「右旋」、斜齿轮 4 取「左旋」（若 $n_1$ 反向，则两轮旋向同时取反）。\n"
    "（3）受力方向：主动轮 1 的 $F_{t1}$ 与其转向相反，从动轮 2 的 $F_{t2}$ 与其转向相同；$F_r$ 一律指向各自轮心；"
    "$F_a$ 按旋向与转向用左右手定则判定。中间轴 Ⅱ 上锥齿轮 2 与斜齿轮 3 的 $F_a$ 方向相反、相互抵消。"
