    "- 要使 Ⅱ 轴轴向力最小，斜齿轮 3 的轴向力 $F_{a3}$ 必须与 $F_{a2}$ 方向相反，据此用左右手定则由 $n_3$ 的转向反推斜齿轮 3 的旋向；\n"
