"""统一修正轴承轴向载荷压紧端判定（2013 / 2015 / 2020）"""
import json

# ============================================================
# 统一判据（写进每个答案里，保持一致）：
# FA 指向哪一端（记为「近端」），压紧端就是近端；
#   Fa(近端) = Fd(远端) + FA ，  Fa(远端) = Fd(远端)
# 并必须校核两组条件：① Fa ≥ 自身 Fd；② 轴上轴向力平衡（Fa近 = Fa远 + FA）。
# 若 Fa(近端) < Fd(近端)，说明 FA 太小、压紧端未变，两轴承仍各取自身 Fd 再加 FA 转移。
# ============================================================

