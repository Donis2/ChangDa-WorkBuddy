# ---------- 2014-计算-01 ----------
q = qs['2014-计算-01']
q['answer'] = (
    "该轮系为行星轮系（系杆 $H$ 为原动件，中心轮 4 固定，$n_4=0$）。转化轮系传动比：\n"
    "$$i_{14}^{H}=\\dfrac{n_1-n_H}{n_4-n_H}=+\\dfrac{z_2\\,z_4}{z_1\\,z_3}=\\dfrac{101\\times99}{100\\times100}=\\dfrac{9999}{10000}=0.9999$$\n"
    "（符号取正：1 为内齿圈与行星轮 2 内啮合、3 与中心轮 4 外啮合，一次内啮合一次外啮合，转化轮系中 1、4 转向相同。）\n"
    "代入 $n_4=0$：\n"
    "$$\\dfrac{n_1-n_H}{-n_H}=0.9999\\Rightarrow n_1-n_H=-0.9999\\,n_H\\Rightarrow n_1=0.0001\\,n_H$$\n"
    "$$\\therefore\\ i_{H1}=\\dfrac{n_H}{n_1}=10000$$\n"
    "$n_1$ 与 $n_H$ 同号，故两者「转向相同」。"
)
q['explanation'] = (
    "考点：行星轮系（大传动比、少齿差型）的转化机构法。关键在于 $i_{14}^{H}$ 的符号：本例 1 是内齿圈、4 是中心轮，"
    "一次内啮合 + 一次外啮合，转化轮系中 1 与 4 同向，故取正号 $+0.9999$；若误取负号会得到 $i_{H1}\\approx0.5$ 的荒谬结果。"
    "齿数差只有 1 齿（100 与 99、101 与 100），所以 $i_{H1}$ 极大（$=10000$），这正是少齿差行星传动能获得大传动比的原因。"
)

