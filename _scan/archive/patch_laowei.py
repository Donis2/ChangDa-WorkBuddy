def main():
    total_ans, total_fix, total_note = 0, 0, 0
    for fn in FILES:
        data = json.load(open(fn, encoding='utf-8'))
        changed = False
        for q in data['questions']:
            qid = q['id']
            # 1) 补答案
            if qid in ANSWERS:
                assert not q.get('answer'), f'{qid} 已有答案，拒绝覆盖'
                q['answer'] = ANSWERS[qid]
                tags = q.setdefault('tags', [])
                if qid in ('2014-简答-03',):
                    if JB not in tags:
                        tags.append(JB)
                else:
                    if LW not in tags:
                        tags.append(LW)
                if '答案待补充' in tags:
                    tags.remove('答案待补充')
                changed = True
                total_ans += 1
            # 2) 选择题更正
            if qid in CHOICE_FIX:
                f = CHOICE_FIX[qid]
                q['answer'] = f['answer']
                q['explanation'] = f['explanation']
                tags = q.setdefault('tags', [])
                if XG not in tags:
                    tags.append(XG)
                changed = True
                total_fix += 1
            # 3) 注记
            if qid in NOTE:
                q['explanation'] = q['explanation'].rstrip() + NOTE[qid]
                changed = True
                total_note += 1
            # 4) 填空修正
            if qid in FILL_FIX:
                q['answer'] = FILL_FIX[qid]
                tags = q.setdefault('tags', [])
                if LW not in tags:
                    tags.append(LW)
                changed = True
        if changed:
            with open(fn, 'w', encoding='utf-8') as fp:
                json.dump(data, fp, ensure_ascii=False, indent=2)
    print(f'补答案 {total_ans} 题，更正选择题 {total_fix} 题，加注记 {total_note} 题，修填空 1 题')


if __name__ == '__main__':
    main()
