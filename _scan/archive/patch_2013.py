qs = {q['id']: q for q in d['questions']}

# ---------- 2013-分析-01 机构自由度 ----------
q = qs['2013-分析-01']
q['answer'] = (
    "（1）三类特殊结构：\n"
    "- 「虚约束」：最上方那根水平横杆。它的两端都插在机架的导路里、与机架组成**移动副**，"
    "两条导路重合，属重复约束——计算时只按 1 个移动副计，多出的 1 个应扣除。\n"
    "- 「复合铰链」：斜杆下端与两根连杆汇交的那个铰点（图中部偏下，三构件汇交，按 2 个转动副计）。\n"
    "- 「局部自由度」：无（本机构中没有滚子）。\n"
    "（2）去除虚约束后：活动构件数 $n=6$（横杆、斜杆、连齿轮 1 的杆、连齿轮 2 的杆、齿轮 1、齿轮 2）；"
    "低副 $P_L=8$（横杆与机架的移动副 1 + 横杆中部铰 1 + 中下复合铰 2 + 齿轮 1 中心 1 + 齿轮 1 上铰点 1 + "
    "齿轮 2 中心 1 + 齿轮 2 上铰点 1）；高副 $P_H=1$（两齿轮啮合）。\n"
    "$$F=3n-2P_L-P_H=3\\times6-2\\times8-1=1$$\n"
    "故机构自由度为 1，需要 1 个原动件即可有确定运动。"
)
q['explanation'] = (
    "考点：复合铰链、局部自由度、虚约束的识别与自由度计算。本题的虚约束是「同一构件与机架组成两个导路重合的移动副」，"
    "计算时只能算一个，否则会得到 $F=0$ 的错误结果；复合铰链在斜杆下端的三杆汇交处（$m=3$，转动副数为 $m-1=2$），"
    "不在顶部横杆与斜杆的铰点上（那里只有 2 个构件）。原手写答案：$F=3\\times6-2\\times8-1=1$、"
    "「虚约束＝最上面两个之一」、「复合铰链＝三杆连接处」，与本答案一致"
    "（原库曾把复合铰链误记到顶部横杆中部，已更正）。"
)

# ---------- 2013-分析-02 蜗杆-斜齿轮 ----------
q = qs['2013-分析-02']
q['answer'] = (
    "（1）蜗轮 4 为「右旋」。\n"
    "（2）斜齿轮 2 也取「右旋」——与蜗轮 4 同旋向。判断依据：轴 Ⅱ 上装着蜗轮 4（由蜗杆 3 驱动，是从动件）"
    "与斜齿轮 2（驱动斜齿轮 1，是主动件），二者转向相同、一主一从；同旋向时两轮的轴向力方向相反，"
    "可以相互抵消，轴 Ⅱ 所受轴向力最小。（若取相反旋向，两轴向力会同向叠加。）\n"
    "（3）蜗杆 3 的转向按图示向下；蜗轮 4 逆时针回转。\n"
    "（4）轴 Ⅱ 上各啮合点的受力：蜗轮 4 与蜗杆 3 的啮合点处，$F_{t4}$ 与蜗轮转向同向、$F_{r4}$ 指向轮心、"
    "$F_{a4}$ 沿轴线方向（由蜗杆的转向与旋向按左右手定则判定）；斜齿轮 2 与斜齿轮 1 的啮合点处，"
    "$F_{t2}$ 与转向相反（主动轮）、$F_{r2}$ 指向轮心、$F_{a2}$ 沿轴向。同一轴上两轮的轴向力方向相反、互相抵消。"
)
q['explanation'] = (
    "考点：蜗杆传动的旋向与转向判定 + 斜齿轮轴向力判定。要点：① 蜗轮与配对蜗杆的旋向相同，故蜗杆 3 也为右旋；"
    "② 判断蜗轮转向用左右手定则（右旋蜗杆用右手：四指顺着蜗杆转向弯曲，拇指指向即蜗轮啮合点的圆周速度方向）；"
    "③ 同轴上一主一从的两个斜齿类零件，螺旋线方向相同时轴向力才反向抵消——这与 2017 年第五题（二级斜齿轮传动）"
    "的结论完全一致。原手写答案给「蜗轮 4 右旋、蜗杆向下、蜗轮 4 逆时针、斜齿轮 2 画右旋」，本答案与之核对一致"
    "（原库曾误记为「斜齿轮 2 与蜗轮 4 旋向应相反」「蜗轮 4 顺时针」，已更正）。"
)
if '答案存疑' in q.get('tags', []):
    q['tags'] = [t for t in q['tags'] if t != '答案存疑']

# ---------- 2013-分析-03 轴的分类 ----------
q = qs['2013-分析-03']
q['answer'] = (
    "$O$：「传动轴」（电动机与减速器之间，只传递转矩，不承受弯矩）。\n"
    "$\\mathrm{II}$：「心轴」（轴上的齿轮为惰轮，只改变转向、不传递转矩，轴只承受弯矩）。\n"
    "$\\mathrm{I}$、$\\mathrm{III}$、$\\mathrm{IV}$：「转轴」（既承受弯矩又传递转矩）。\n"
    "$\\mathrm{V}$（卷筒轴）：「心轴」。转矩由大齿轮直接传给卷筒，卷筒再带动钢丝绳，轴只起支承作用、"
    "不传递转矩，故只承受弯矩；轴随卷筒一起转动时属「转动心轴」。"
)
q['explanation'] = (
    "考点：按承载情况给轴分类——只受弯矩为心轴（转动心轴 / 固定心轴），只受转矩为传动轴，两者都受为转轴。"
    "本题的关键是 $\\mathrm{V}$：卷筒轴虽随卷筒转动，但转矩走的是「大齿轮 $\\rightarrow$ 卷筒」这条路径，"
    "轴本身不传转矩，因此是心轴而不是转轴。原手写答案把 $\\mathrm{V}$ 归为转轴，"
    "按教材口径应为心轴，此处按原理更正；其余 $O$、$\\mathrm{I}\\sim\\mathrm{IV}$ 的判定与原答案一致。"
)
q['tags'] = ['已修正原答案']

